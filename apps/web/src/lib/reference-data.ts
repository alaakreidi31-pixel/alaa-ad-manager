export interface Option {
  value: string;
  label: string;
}

function displayName(type: 'region' | 'currency', code: string, language: string): string {
  try {
    return new Intl.DisplayNames([language], { type }).of(code) ?? code;
  } catch {
    return code;
  }
}

// Sorted by name in the page language, e.g. "السعودية (SA)".
export function countryOptions(language: string): Option[] {
  return COUNTRY_CODES.map((code) => ({
    value: code,
    label: `${displayName('region', code, language)} (${code})`,
  })).sort((a, b) => a.label.localeCompare(b.label, language));
}

// The most used currencies first, then all the others.
const FIRST_CURRENCIES = [
  'USD',
  'SAR',
  'AED',
  'EUR',
  'GBP',
  'KWD',
  'QAR',
  'BHD',
  'OMR',
  'EGP',
  'JOD',
  'TRY',
];

export function currencyOptions(language: string): Option[] {
  const all = Intl.supportedValuesOf('currency');
  const rest = all.filter((code) => !FIRST_CURRENCIES.includes(code));
  return [...FIRST_CURRENCIES.filter((code) => all.includes(code)), ...rest].map((code) => ({
    value: code,
    label: `${code} - ${displayName('currency', code, language)}`,
  }));
}

export function timeZoneOptions(): string[] {
  return ['UTC', ...Intl.supportedValuesOf('timeZone').filter((zone) => zone !== 'UTC')];
}
